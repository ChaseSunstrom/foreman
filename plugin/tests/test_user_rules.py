"""T-0971: fm rule, the user's own regex rules on Bash commands or edited paths: a block denies with the user's why,
a warn is a note; removing one is the user's call; a recorded veto can become one."""
import json
import os
import time

from helpers import ForemanTestCase

import fmcore as c


def _out(proc):
    try:
        return json.loads(proc.stdout or "{}").get("hookSpecificOutput") or {}
    except ValueError:
        return {}


class UserRules(ForemanTestCase):
    def setUp(self):
        super().setUp()
        self.fm("init")
        self.fm("task", "new", "Ship it", "--type", "FEATURE", "--tier", "S", "--ac", "x :: true", "--step", "x",
                "--focus")

    def bash(self, cmd):
        return self.hook("PreToolUse", {"tool_name": "Bash", "tool_input": {"command": cmd}})

    def edit(self, rel):
        return self.hook("PreToolUse", {"tool_name": "Edit", "tool_input": {
            "file_path": os.path.join(self.repo, rel), "old_string": "a", "new_string": "b"}})

    def test_a_block_rule_denies_a_matching_command_with_the_why(self):
        self.fm("rule", "add", "git push.*main", "--on", "bash", "--block", "--why", "release.py pushes")
        p = self.bash("git push origin main")
        self.assertEqual(p.returncode, 2)
        self.assertEqual(_out(p).get("permissionDecision"), "deny")
        self.assertIn("release.py pushes", _out(p).get("permissionDecisionReason", ""))
        self.assertEqual(self.bash("git status").returncode, 0)
        self.assertIn("git push.*main", self.fm("rule", "list").stdout)

    def test_a_warn_rule_is_a_note_and_the_call_runs(self):
        self.fm("rule", "add", "make deploy", "--warn", "--why", "ask before deploying")
        p = self.bash("make deploy ENV=prod")
        self.assertEqual(p.returncode, 0)
        self.assertNotEqual(_out(p).get("permissionDecision"), "deny")
        self.assertIn("ask before deploying", _out(p).get("additionalContext", ""))

    def test_a_path_rule_matches_an_edited_file_not_a_command(self):
        self.fm("rule", "add", r"migrations/.*\.sql$", "--on", "path", "--block", "--why", "generated by alembic")
        p = self.edit("migrations/0001.sql")
        self.assertEqual(p.returncode, 2)
        self.assertIn("generated by alembic", _out(p).get("permissionDecisionReason", ""))
        self.assertEqual(self.edit("app.py").returncode, 0)
        self.assertEqual(self.bash("cat migrations/0001.sql").returncode, 0, "reading the file is fine")
        # security review: a Bash write to the path is an edit too, and a symlink doesn't hide the real path
        self.assertEqual(self.bash("sed -i s/a/b/ migrations/0001.sql").returncode, 2)
        self.assertEqual(self.bash("echo x > migrations/0002.sql").returncode, 2)
        os.makedirs(os.path.join(self.repo, "migrations"), exist_ok=True)
        open(os.path.join(self.repo, "migrations", "0003.sql"), "w").close()
        os.symlink(os.path.join(self.repo, "migrations", "0003.sql"), os.path.join(self.repo, "alias.txt"))
        self.assertEqual(self.edit("alias.txt").returncode, 2)

    def test_a_long_command_cant_outrun_a_block_rule(self):
        # security review: padding a command past the scan cap used to hide the match
        self.fm("rule", "add", "git push.*main", "--on", "bash", "--block", "--why", "release.py pushes")
        self.assertEqual(self.bash("echo " + "x" * 5000 + " && git push origin main").returncode, 2)

    def test_python_calling_the_rule_store_directly_is_refused(self):
        import fmguard
        ctx = fmguard.Ctx(cwd=self.repo, project_root=self.repo, home=self.tmp, foreman_home=self.home,
                          state_dir=c.state_dir(), state_fallbacks=[])
        for code in ("from fmcore import drop_rule; drop_rule(p, 1)", "import fmcore as c\nc.drop_veto(p, 1)"):
            found = fmguard.check_bash(f"python3 - <<'EOF'\n{code}\nEOF", ctx)
            self.assertTrue(found, code)

    def test_a_bad_or_overlong_regex_is_refused_at_add_time(self):
        self.assertNotEqual(self.fm("rule", "add", "(unclosed", "--why", "x", check=False).returncode, 0)
        self.assertNotEqual(self.fm("rule", "add", "a" * (c.RULE_MAX + 1), "--why", "x", check=False).returncode, 0)
        self.assertNotEqual(self.fm("rule", "add", "", "--why", "x", check=False).returncode, 0)
        self.assertEqual(c.rules(c.find_project(self.repo)), [])

    def test_a_slow_pattern_is_time_boxed_and_a_block_fails_closed(self):
        self.fm("rule", "add", "(a+)+$", "--block", "--why", "nested")
        t = time.time()
        p = self.bash("echo " + "a" * 40 + "!")
        self.assertLess(time.time() - t, 4)  # wall clock: the rule's time-box deadline, in a hook child
        self.assertEqual(p.returncode, 2, "a block rule it couldn't finish checking refuses")
        self.assertIn("too long", _out(p).get("permissionDecisionReason", ""))
        # security review: past RULE_SCAN a block rule can't be shown not to match, so it refuses (a warn doesn't)
        self.fm("rule", "rm", "1")
        self.fm("rule", "add", "TAIL", "--block", "--why", "x")
        self.assertEqual(self.bash("echo " + "x" * c.RULE_SCAN + " ok").returncode, 2)
        self.assertEqual(self.bash("echo ok").returncode, 0)

    def test_removing_a_rule_is_the_users_call(self):
        import fmguard
        ctx = fmguard.Ctx(cwd=self.repo, project_root=self.repo, home=self.tmp, foreman_home=self.home,
                          state_dir=c.state_dir(), state_fallbacks=[])
        cats = lambda cmd: [cat for cat, _ in fmguard.check_bash(cmd, ctx)]  # noqa: E731
        for cmd in ("fm rule rm 1", "fm rule --json rm 1", "fm rule -p x rm 1"):
            self.assertIn("self-authorize", cats(cmd), cmd)
        for cmd in ("fm rule", "fm rule list", "fm rule add 'git push' --block --why x", "fm rule add --from-veto 1"):
            self.assertNotIn("self-authorize", cats(cmd), cmd)
        self.fm("rule", "add", "git push", "--block", "--why", "x")
        self.assertEqual(self.bash("fm rule rm 1").returncode, 2)
        self.fm("rule", "rm", "1")  # the user, at their prompt
        self.assertEqual(self.bash("git push origin main").returncode, 0)
        self.assertNotEqual(self.fm("rule", "rm", "3", check=False).returncode, 0)

    def test_a_veto_becomes_a_rule(self):
        self.hook("UserPromptSubmit", {"prompt": "never push without asking me first"})
        self.fm("rule", "add", "--from-veto", "1")
        p = self.bash("git push origin main")
        self.assertEqual(p.returncode, 2)
        self.assertIn("never push without asking me first", _out(p).get("permissionDecisionReason", ""))
        self.assertEqual(self.bash("git status").returncode, 0)
        self.assertNotEqual(self.fm("rule", "add", "--from-veto", "9", check=False).returncode, 0)
